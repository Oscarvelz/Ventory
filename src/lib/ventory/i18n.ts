/**
 * Ventory's language table (1.11.0). The app speaks English and Spanish as
 * first-class languages of the house: every label, message and composed
 * sentence the interface shows lives here (or in a per-language template set
 * in the sentence builders), never as an inline literal in a component.
 * The chosen language is a device/account preference, stored with the theme
 * in the pref record; a localStorage mirror lets the pre-sign-in doors and
 * the pre-React failure shell speak it too.
 */
export type Lang = "en" | "es";

export function asLang(value: unknown): Lang {
  return value === "es" ? "es" : "en";
}

const MIRROR = "ventory.lang";

export function mirrorLang(lang: Lang): void {
  try {
    localStorage.setItem(MIRROR, lang);
  } catch {
    /* the mirror is a courtesy for the doors; the pref record is the truth */
  }
}

export function mirroredLang(): Lang {
  try {
    return asLang(localStorage.getItem(MIRROR));
  } catch {
    return "en";
  }
}

