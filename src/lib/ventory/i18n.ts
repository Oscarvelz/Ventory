export type StrKey = keyof typeof STR;

/** Resolve a table string in the given language, filling {name} slots. */
export function tx(lang: Lang, key: StrKey, vars?: Record<string, string | number>): string {
  let out: string = STR[key][lang];
  if (vars) for (const [name, value] of Object.entries(vars)) out = out.replaceAll(`{${name}}`, String(value));
  return out;
}

/** "Nov 2026" / "nov 2026" — month + year in the house language. */
export function monthYear(lang: Lang, year: number, monthIndex: number): string {
  return new Intl.DateTimeFormat(lang === "es" ? "es" : "en", { month: "short", year: "numeric" }).format(new Date(year, monthIndex, 1));
}

/** "Nov 16, 2026" / "16 nov 2026" — a full date in the house language. */
export function fullDate(lang: Lang, iso: string): string {
  const d = new Date(`${iso}T12:00:00`);
  if (Number.isNaN(d.getTime())) return iso;
  return new Intl.DateTimeFormat(lang === "es" ? "es" : "en", { month: "short", day: "numeric", year: "numeric" }).format(d);
}
